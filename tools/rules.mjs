// Generates supabase/rules.sql from supabase/functions/_shared/rules.js.
// Usage: node tools/rules.mjs > supabase/rules.sql, then run this file in Supabase after every rule change.
import { readFileSync } from 'node:fs';
new Function(readFileSync(new URL('../supabase/functions/_shared/rules.js', import.meta.url), 'utf8'))();
const { B, ITEM, RECIPES, reqTier, placeIds, COSMETICS, SET_EUR } = globalThis.Rules;
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'string' ? `'${v.replace(/'/g, "''")}'` : String(v));
const kindOf = (b) => (b.water ? 'water' : b.x != null ? 'cross' : b.shape || 'cube');
const blocks = [], place = [], items = [], recipes = [], cosmetics = [];
for (const [k, b] of Object.entries(B)) {
  const id = +k, drop = b.drop === undefined ? id : b.drop;
  const solid = !b.water && b.x == null && !b.pass;
  blocks.push(`(${id},${q(b.n)},${b.h === Infinity || b.h === undefined ? 'null' : b.h},${reqTier(id)},${drop ? drop : 'null'},${q(kindOf(b))},${solid},${!!b.top})`);
}
const unobtainable = new Set([11, 12, 73, 74]);
for (const k of Object.keys(B)) { const id = +k, b = B[id]; if (unobtainable.has(id)) continue; if (b.drop !== undefined && b.drop !== id) continue; for (const p of placeIds(id)) place.push(`(${id},${p})`); }
for (const [k, it] of Object.entries(ITEM)) items.push(`(${+k},${q(it.n)},${it.tool || 1},${it.tier || 0},${!!it.nft},${!!it.use})`);
for (const r of RECIPES) recipes.push(`(${r.out},${r.n},${q(JSON.stringify(r.need))}::jsonb,${!!r.nft},${r.req || 'null'})`);
for (const [k, c] of Object.entries(COSMETICS)) cosmetics.push(`(${+k},${q(c.n)},${c.price},${q(c.category)},${q(c.grantItem)},${q(c.grantQty)},${!!c.limited},${q(c.eur)},${q(c.category === 'premium' ? c.set : null)})`);
const sets = Object.entries(SET_EUR).map(([k, e]) => `(${q(k)},${e})`);
console.log(`-- Game rules for server-side arbitration. FILE GENERATED by tools/rules.mjs: do not edit by hand.
-- Re-run in Supabase (SQL Editor) after every change to supabase/functions/_shared/rules.js.
begin;
delete from public.rule_blocks; delete from public.rule_place; delete from public.rule_items; delete from public.rule_recipes;
delete from public.rule_cosmetics; delete from public.rule_sets;
insert into public.rule_blocks (id, name, hard, tier, drop_item, kind, solid, top) values
${blocks.join(',\n')};
insert into public.rule_place (item, block) values
${place.join(',\n')};
insert into public.rule_items (id, name, tool, tier, uniq, consumable) values
${items.join(',\n')};
insert into public.rule_recipes (out_item, n, need, uniq, req_unique) values
${recipes.join(',\n')};
insert into public.rule_cosmetics (id, name, price, category, grant_item, grant_qty, limited, eur, set_id) values
${cosmetics.join(',\n')};
insert into public.rule_sets (id, eur) values
${sets.join(',\n')};
commit;`);
