// Ether Mines · exports the game rules (supabase/functions/_shared/rules.js, the single source of truth) to
// unity/Assets/Resources/rules.json, read by the Unity client (Rules.cs, through MiniJson.cs).
// Run after any change to rules.js:  node unity/tools/export-rules.mjs
//
// Format notes (also written into the file as "_format"):
// - Same shapes as rules.js: B, ITEM, COSMETICS, SETS, SET_EUR are objects keyed by id (string keys, ascending),
//   RECIPES an array in rules.js order, PASTELS / STAINED arrays of [name, color].
// - Keys inside an entry keep rules.js's order. One entry per line.
// - Non-finite numbers (Bedrock's h: Infinity) are written as the strings "Infinity", "-Infinity", "NaN".
// - "shop" holds the constants behind the functions shopWeek / shopFeatured / shopPrice / forSale, read
//   from rules.js itself and checked against the functions before writing. reqTier and placeIds only read
//   B. The functions are ported to C# in Rules.cs (CoreTests checks them against rules.js).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
globalThis.window = globalThis;
require('../../supabase/functions/_shared/world.js');
require('../../supabase/functions/_shared/rules.js');
const R = globalThis.Rules;
const src = readFileSync(new URL('../../supabase/functions/_shared/rules.js', import.meta.url), 'utf8');

const fail = m => {
  throw new Error('export-rules: ' + m);
};
// ---------- the shop's constants, read from rules.js and checked against its functions ----------
const epoch = +(/const SHOP_EPOCH = (\d+)/.exec(src) || fail('SHOP_EPOCH not found'))[1];
const weekM = /Math\.floor\(\(t - SHOP_EPOCH\) \/ (\d+)\)/.exec(R.shopWeek.toString()) || fail('shopWeek changed shape');
const week = +weekM[1];
const fsM = /!\[([^\]]*)\]\.includes\(c\.category\) && c\.price > 0/.exec(R.forSale.toString()) || fail('forSale changed shape');
const notForSale = JSON.parse('[' + fsM[1].replace(/'/g, '"') + ']');
const shop = { epoch, week, notForSale, saleCount: 3, saleNum: 3, saleDen: 4 };
if (R.shopWeek(epoch) !== 0 || R.shopWeek(epoch + week) !== 1 || R.shopWeek(epoch - 1) !== -1) fail('shopWeek mismatch');
for (const [id, c] of Object.entries(R.COSMETICS)) {
  if (R.forSale(c) !== (!notForSale.includes(c.category) && c.price > 0)) fail('forSale mismatch on ' + id);
  for (const w of [0, 7, 1000]) {
    const on = R.shopFeatured(w).sale.includes(+id);
    if (R.shopPrice(id, w) !== (on ? Math.floor((c.price * shop.saleNum) / shop.saleDen) : c.price)) fail('shopPrice mismatch on ' + id);
  }
}
for (const w of [0, 5, 99]) if (R.shopFeatured(w).sale.length !== shop.saleCount) fail('shopFeatured sale count');
// setPrice: the set's price times the share (in euros) of the pieces still missing, rounded half up
for (const set of Object.keys(R.SET_EUR)) {
  const all = R.setPieces(set),
    sum = l => l.reduce((t, id) => t + R.COSMETICS[id].eur, 0);
  for (let k = 0; k <= all.length; k++) {
    const own = id => all.indexOf(id) < k;
    const want = k === all.length ? 0 : Math.floor((R.SET_EUR[set] * sum(all.slice(k))) / sum(all) + 0.5);
    if (R.setPrice(set, own) !== want) fail('setPrice mismatch on ' + set);
  }
}

// ---------- writing ----------
const val = v => JSON.stringify(v, (k, x) => (typeof x === 'number' && !Number.isFinite(x) ? String(x) : x));
const obj = o =>
  '{\n' +
  Object.entries(o)
    .map(([k, v]) => '    ' + JSON.stringify(k) + ': ' + val(v))
    .join(',\n') +
  '\n  }';
const arr = a => '[\n' + a.map(v => '    ' + val(v)).join(',\n') + '\n  ]';
const FORMAT =
  'Generated by unity/tools/export-rules.mjs from supabase/functions/_shared/rules.js: do not edit. ' +
  'Non-finite numbers are the strings "Infinity", "-Infinity", "NaN". ' +
  'shop: constants of shopWeek (floor((t - epoch) / week)), shopFeatured (saleCount picks), shopPrice (price * saleNum / saleDen), forSale (category not in notForSale and price > 0).';
const parts = [
  ['_format', val(FORMAT)],
  ['B', obj(R.B)],
  ['ITEM', obj(R.ITEM)],
  ['RECIPES', arr(R.RECIPES)],
  ['COSMETICS', obj(R.COSMETICS)],
  ['SETS', obj(R.SETS)],
  ['SET_EUR', val(R.SET_EUR)],
  ['PASTELS', val(R.PASTELS)],
  ['STAINED', val(R.STAINED)],
  ['shop', val(shop)],
];
const out = '{\n' + parts.map(([k, v]) => '  ' + JSON.stringify(k) + ': ' + v).join(',\n') + '\n}\n';
// round trip: what's written must read back as rules.js (apart from the non-finite numbers)
const back = JSON.parse(out);
if (val(back.B) !== val(R.B) || val(back.COSMETICS) !== val(R.COSMETICS) || val(back.RECIPES) !== val(R.RECIPES)) fail('round trip');
// --check: say whether rules.json is up to date, without writing it (tests/unity.test.mjs)
const dest = new URL('../Assets/Resources/rules.json', import.meta.url);
if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(dest, 'utf8');
  } catch {}
  if (cur !== out) fail('unity/Assets/Resources/rules.json is out of date: node unity/tools/export-rules.mjs');
  process.exit(0);
}
writeFileSync(dest, out);
console.log('wrote', dest.pathname, out.length, 'bytes');
